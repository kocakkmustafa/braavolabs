registerTool({
  name: "store_memory",
  description:
    "Store a new memory item (episodic, semantic, or procedural). Memories start as CANDIDATE status.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      type: { type: "string", enum: ["EPISODIC", "SEMANTIC", "PROCEDURAL"] },
      content: { type: "string", description: "Memory content to store" },
      confidence: { type: "number", description: "Confidence score 0-1", default: 0.5 },
      source: { type: "string", description: "Source of this memory (e.g. run ID)" },
    },
    required: ["companyId", "type", "content"],
  },
  handler: async (input) => {
    const { companyId, type, content, confidence, source } = input as {
      companyId: string;
      type: string;
      content: string;
      confidence?: number;
      source?: string;
    };

    // CRITICAL: Memory starts as CANDIDATE — never directly APPROVED
    const memory = await prisma.memoryItem.create({
      data: {
        companyId,
        type: type as any,
        status: "CANDIDATE",
        content,
        confidence: confidence ?? 0.5,
        source,
      },
    });

    logger.info({ memoryId: memory.id, type }, "Memory stored as candidate");
    return { memoryId: memory.id, type, status: "CANDIDATE" };
  },
});

registerTool({
  name: "recall_memory",
  description:
    "Search and recall relevant memories for a given query. Returns matching memory items.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      query: { type: "string", description: "Search query" },
      type: { type: "string", enum: ["EPISODIC", "SEMANTIC", "PROCEDURAL"] },
      limit: { type: "number", description: "Max results", default: 5 },
    },
    required: ["companyId", "query"],
  },
  handler: async (input) => {
    const { companyId, query, type, limit } = input as {
      companyId: string;
      query: string;
      type?: string;
      limit?: number;
    };

    // Text-based search until pgvector semantic search is implemented (Faz 2)
    const memories = await prisma.memoryItem.findMany({
      where: {
        companyId,
        status: { in: ["CANDIDATE", "APPROVED"] },
        ...(type && { type: type as any }),
        content: { contains: query, mode: "insensitive" },
      },
      orderBy: [{ status: "desc" }, { confidence: "desc" }],
      take: limit ?? 5,
    });

    // Update use counts
    if (memories.length > 0) {
      await prisma.memoryItem.updateMany({
        where: { id: { in: memories.map((m) => m.id) } },
        data: { useCount: { increment: 1 }, lastUsedAt: new Date() },
      });
    }

    return {
      query,
      results: memories.map((m) => ({
        id: m.id,
        type: m.type,
        status: m.status,
        content: m.content,
        confidence: m.confidence,
        useCount: m.useCount,
      })),
    };
  },
});

registerTool({
  name: "consolidate_memories",
  description:
    "Trigger memory consolidation — promote high-confidence candidates, deprecate stale ones.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
    },
    required: ["companyId"],
  },
  handler: async (input) => {
    const { companyId } = input as { companyId: string };

    // Promote candidates with high confidence and use count
    const promoted = await prisma.memoryItem.updateMany({
      where: {
        companyId,
        status: "CANDIDATE",
        confidence: { gte: 0.8 },
        useCount: { gte: 3 },
      },
      data: { status: "APPROVED", promotedAt: new Date() },
    });

    // Deprecate stale approved memories (not used in 90 days)
    const staleDate = new Date();
    staleDate.setDate(staleDate.getDate() - 90);
    const deprecated = await prisma.memoryItem.updateMany({
      where: {
        companyId,
        status: "APPROVED",
        lastUsedAt: { lt: staleDate },
      },
      data: { status: "DEPRECATED" },
    });

    return {
      companyId,
      promoted: promoted.count,
      deprecated: deprecated.count,
    };
  },
});

