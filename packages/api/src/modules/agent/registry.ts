registerTool({
  name: "fetch_metrics",
  description:
    "Fetch performance metrics for a company's content and operations. Returns key metrics.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      metric: {
        type: "string",
        enum: ["runs", "drafts", "tool_calls", "costs", "all"],
        description: "Which metric to fetch",
      },
      periodDays: { type: "number", description: "Number of days to look back", default: 30 },
    },
    required: ["companyId", "metric"],
  },
  handler: async (input) => {
    const { companyId, metric, periodDays } = input as {
      companyId: string;
      metric: string;
      periodDays?: number;
    };

    const since = new Date();
    since.setDate(since.getDate() - (periodDays ?? 30));

    const results: Record<string, unknown> = { companyId, period: { since: since.toISOString() } };

    if (metric === "runs" || metric === "all") {
      const runs = await prisma.run.count({
        where: {
          pipeline: { companyId },
          createdAt: { gte: since },
        },
      });
      const completed = await prisma.run.count({
        where: {
          pipeline: { companyId },
          status: "COMPLETED",
          createdAt: { gte: since },
        },
      });
      results.runs = { total: runs, completed, successRate: runs > 0 ? completed / runs : 0 };
    }

    if (metric === "drafts" || metric === "all") {
      const drafts = await prisma.draft.count({
        where: { companyId, createdAt: { gte: since } },
      });
      const published = await prisma.draft.count({
        where: { companyId, status: "PUBLISHED", createdAt: { gte: since } },
      });
      results.drafts = { total: drafts, published };
    }

    if (metric === "tool_calls" || metric === "all") {
      const toolCalls = await prisma.toolCall.count({
        where: {
          runStep: { run: { pipeline: { companyId } } },
          createdAt: { gte: since },
        },
      });
      results.toolCalls = { total: toolCalls };
    }

    return results;
  },
});

registerTool({
  name: "generate_report",
  description: "Generate a summary report of company performance and key insights.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      reportType: {
        type: "string",
        enum: ["daily", "weekly", "monthly"],
        description: "Report period type",
      },
    },
    required: ["companyId", "reportType"],
  },
  handler: async (input) => {
    const { companyId, reportType } = input as { companyId: string; reportType: string };

    const daysMap: Record<string, number> = { daily: 1, weekly: 7, monthly: 30 };
    const days = daysMap[reportType] ?? 7;
    const since = new Date();
    since.setDate(since.getDate() - days);

    const [runCount, draftCount, stepCount] = await Promise.all([
      prisma.run.count({ where: { pipeline: { companyId }, createdAt: { gte: since } } }),
      prisma.draft.count({ where: { companyId, createdAt: { gte: since } } }),
      prisma.runStep.count({
        where: { run: { pipeline: { companyId } }, createdAt: { gte: since } },
      }),
    ]);

    return {
      companyId,
      reportType,
      period: { from: since.toISOString(), to: new Date().toISOString() },
      summary: { runs: runCount, drafts: draftCount, steps: stepCount },
      note: "Agent should interpret these numbers and provide insights in response.",
    };
  },
});

registerTool({
  name: "compare_performance",
  description: "Compare performance between two time periods for a company.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      currentDays: { type: "number", description: "Current period (days)", default: 7 },
      previousDays: { type: "number", description: "Previous period (days)", default: 7 },
    },
    required: ["companyId"],
  },
  handler: async (input) => {
    const { companyId, currentDays, previousDays } = input as {
      companyId: string;
      currentDays?: number;
      previousDays?: number;
    };

    const now = new Date();
    const currentStart = new Date(now);
    currentStart.setDate(currentStart.getDate() - (currentDays ?? 7));
    const previousStart = new Date(currentStart);
    previousStart.setDate(previousStart.getDate() - (previousDays ?? 7));

    const [currentRuns, previousRuns] = await Promise.all([
      prisma.run.count({
        where: { pipeline: { companyId }, createdAt: { gte: currentStart } },
      }),
      prisma.run.count({
        where: {
          pipeline: { companyId },
          createdAt: { gte: previousStart, lt: currentStart },
        },
      }),
    ]);

    const change = previousRuns > 0
      ? ((currentRuns - previousRuns) / previousRuns) * 100
      : currentRuns > 0 ? 100 : 0;

    return {
      companyId,
      current: { runs: currentRuns, period: `last ${currentDays ?? 7} days` },
      previous: { runs: previousRuns, period: `previous ${previousDays ?? 7} days` },
      changePercent: Math.round(change * 100) / 100,
    };
  },
});

