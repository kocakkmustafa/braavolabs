registerTool({
  name: "create_draft",
  description:
    "Save a content draft to the database for review before publishing. Returns the draft ID.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      type: {
        type: "string",
        enum: ["SOCIAL_POST", "EMAIL", "BLOG_POST", "AD_COPY", "VIDEO_SCRIPT"],
      },
      title: { type: "string", description: "Draft title" },
      body: { type: "string", description: "Draft body content" },
      channel: { type: "string", description: "Target channel (tiktok, linkedin, etc.)" },
      hashtags: {
        type: "array",
        items: { type: "string" },
        description: "Hashtags for the post",
      },
    },
    required: ["companyId", "type", "title", "body"],
  },
  handler: async (input) => {
    const { companyId, type, title, body, channel, hashtags } = input as {
      companyId: string;
      type: string;
      title: string;
      body: string;
      channel?: string;
      hashtags?: string[];
    };

    // Resolve company: try by ID first, then by slug
    let resolvedCompanyId = companyId;
    const companyById = await prisma.company.findUnique({ where: { id: companyId } }).catch(() => null);
    if (!companyById) {
      const companyBySlug = await prisma.company.findFirst({ where: { slug: companyId } });
      if (companyBySlug) {
        resolvedCompanyId = companyBySlug.id;
      } else {
        return { error: `Company not found: ${companyId}`, status: "FAILED" };
      }
    }

    const draft = await prisma.draft.create({
      data: {
        companyId: resolvedCompanyId,
        type: type as any,
        title,
        content: { body, hashtags: hashtags ?? [] },
        channel,
        status: "PENDING",
      },
    });

    logger.info({ draftId: draft.id, type, channel }, "Draft created via tool");
    return { draftId: draft.id, status: "PENDING", title };
  },
});

