registerTool({
  name: "compare_performance",
  description: "Compare performance between two time periods for a company.",
  inputSchema: {
    type: "object" as const,
    properties: {
      companyId: { type: "string", description: "Company ID" },
      currentDays: { type: "number", description: "Current period (days)", default: 7 },
      previousDays: { type: "number", description: "Previous period (days)", default: 7 },
    },
    required: ["companyId"],
  },
  handler: async (input) => {
    const { companyId, currentDays, previousDays } = input as {
      companyId: string;
      currentDays?: number;
      previousDays?: number;
    };

    const now = new Date();
    const currentStart = new Date(now);
    currentStart.setDate(currentStart.getDate() - (currentDays ?? 7));
    const previousStart = new Date(currentStart);
    previousStart.setDate(previousStart.getDate() - (previousDays ?? 7));

    const [currentRuns, previousRuns] = await Promise.all([
      prisma.run.count({
        where: { pipeline: { companyId }, createdAt: { gte: currentStart } },
      }),
      prisma.run.count({
        where: {
          pipeline: { companyId },
          createdAt: { gte: previousStart, lt: currentStart },
        },
      }),
    ]);

    const change = previousRuns > 0
      ? ((currentRuns - previousRuns) / previousRuns) * 100
      : currentRuns > 0 ? 100 : 0;

    return {
      companyId,
      current: { runs: currentRuns, period: `last ${currentDays ?? 7} days` },
      previous: { runs: previousRuns, period: `previous ${previousDays ?? 7} days` },
      changePercent: Math.round(change * 100) / 100,
    };
  },
});

