// ─── Lookup helpers ───────────────────────────────────────

export function getWebhookTemplates(category?: string): WebhookTemplate[] {
  if (!category) {
    return [...WEBHOOK_TEMPLATES].sort((a, b) => b.popularity - a.popularity);
  }
  return WEBHOOK_TEMPLATES
    .filter((t) => t.category === category)
    .sort((a, b) => b.popularity - a.popularity);
}

export function getWebhookTemplateById(id: string): WebhookTemplate | undefined {
  return WEBHOOK_TEMPLATES.find((t) => t.id === id);
}

export function getWebhookTemplateCategories(): { category: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const t of WEBHOOK_TEMPLATES) {
    counts.set(t.category, (counts.get(t.category) || 0) + 1);
  }
  return Array.from(counts.entries())
    .map(([category, count]) => ({ category, count }))
    .sort((a, b) => b.count - a.count);
}
