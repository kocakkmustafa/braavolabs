/**
 * Returns the full integration catalog, optionally filtered.
 */
export function getIntegrationCatalog(filter?: IntegrationCatalogFilter): IntegrationConnector[] {
  let results = [...CATALOG];

  if (filter?.category) {
    results = results.filter((c) => c.category === filter.category);
  }
  if (filter?.status) {
    results = results.filter((c) => c.status === filter.status);
  }
  if (filter?.search) {
    const q = filter.search.toLowerCase();
    results = results.filter(
      (c) =>
        c.name.toLowerCase().includes(q) ||
        c.description.toLowerCase().includes(q) ||
        c.category.toLowerCase().includes(q) ||
        c.features.some((f) => f.toLowerCase().includes(q)) ||
        c.popularActions.some((a) => a.toLowerCase().includes(q)),
    );
  }

  return results;
}

/**
 * Returns connectors for a specific category.
 */
export function getIntegrationsByCategory(category: IntegrationCategory): IntegrationConnector[] {
  return CATALOG.filter((c) => c.category === category);
}

/**
 * Free-text search across name, description, features, and actions.
 */
export function searchIntegrations(query: string): IntegrationConnector[] {
  const q = query.toLowerCase();
  return CATALOG.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.description.toLowerCase().includes(q) ||
      c.category.toLowerCase().includes(q) ||
      c.features.some((f) => f.toLowerCase().includes(q)) ||
      c.popularActions.some((a) => a.toLowerCase().includes(q)),
  );
}

/**
 * Returns a single connector by ID, or undefined if not found.
 */
export function getIntegrationById(id: string): IntegrationConnector | undefined {
  return CATALOG.find((c) => c.id === id);
}
